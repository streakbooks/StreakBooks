#!/usr/bin/env node
/**
 * Generates billing ISO reference data from official sources:
 *   - ISO 4217 List One (SIX Group, maintenance agency) for currency codes and minor units
 *   - Unicode CLDR supplemental currencyData for each territory's current legal tender
 *   - Unicode CLDR English territory names
 * Country codes come from src/lib/billing/billing-countries.ts (ISO 3166-1 alpha-2).
 *
 * Usage:
 *   curl -o /tmp/list-one.xml https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml
 *   curl -o /tmp/currencyData.json https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-core/supplemental/currencyData.json
 *   curl -o /tmp/territories.json https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/cldr-localenames-full/main/en/territories.json
 *   node scripts/generate-billing-reference-data.mjs /tmp/list-one.xml /tmp/currencyData.json /tmp/territories.json > /tmp/seed.sql
 *   npx prettier --write src/lib/billing/reference/iso-reference-data.ts
 *
 * Writes src/lib/billing/reference/iso-reference-data.ts and prints the SQL seed to stdout.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const [isoPath, cldrPath, namesPath] = process.argv.slice(2);
if (!isoPath || !cldrPath || !namesPath) {
  console.error(
    "Usage: generate-billing-reference-data.mjs <list-one.xml> <currencyData.json> <territories.json>",
  );
  process.exit(2);
}

const xml = readFileSync(isoPath, "utf8");
const published = /Pblshd="([^"]+)"/.exec(xml)?.[1] ?? "unknown";
const currencies = new Map();
for (const entry of xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)) {
  const body = entry[1];
  const code = /<Ccy>([A-Z]{3})<\/Ccy>/.exec(body)?.[1];
  const numeric = /<CcyNbr>(\d{3})<\/CcyNbr>/.exec(body)?.[1];
  const nameMatch = /<CcyNm( IsFund="true")?>([^<]+)<\/CcyNm>/.exec(body);
  const minor = /<CcyMnrUnts>([^<]+)<\/CcyMnrUnts>/.exec(body)?.[1];
  if (!code || !numeric || !nameMatch || !minor) continue;
  if (nameMatch[1]) continue; // fund codes are not billing currencies
  if (!/^\d$/.test(minor)) continue; // N.A. (precious metals, testing, SDR)
  if (!currencies.has(code)) {
    currencies.set(code, {
      code,
      numericCode: numeric,
      name: nameMatch[2].trim(),
      minorUnits: Number(minor),
    });
  }
}

const cldr = JSON.parse(readFileSync(cldrPath, "utf8"));
const cldrVersion = cldr.supplemental.version._cldrVersion;
const regions = cldr.supplemental.currencyData.region;
const names = JSON.parse(readFileSync(namesPath, "utf8")).main.en.localeDisplayNames.territories;

const countrySource = readFileSync(path.join(root, "src/lib/billing/billing-countries.ts"), "utf8");
const codeBlock = /const COUNTRY_CODES = `([\s\S]*?)`/.exec(countrySource)?.[1];
if (!codeBlock) throw new Error("COUNTRY_CODES not found in billing-countries.ts");
const countryCodes = codeBlock.trim().split(/\s+/).sort();

function currentTender(code) {
  const entries = (regions[code] ?? []).flatMap((o) => Object.entries(o));
  const current = entries
    .filter(([, v]) => !v._to && v._tender !== "false")
    .filter(([c]) => currencies.has(c))
    .sort((a, b) => String(b[1]._from ?? "").localeCompare(String(a[1]._from ?? "")));
  return current[0]?.[0] ?? null;
}

const countries = countryCodes.map((code) => ({
  code,
  name: names[code] ?? code,
  defaultCurrency: currentTender(code),
}));
const currencyList = [...currencies.values()].sort((a, b) => a.code.localeCompare(b.code));

const ts = `// Generated by scripts/generate-billing-reference-data.mjs. Do not edit by hand.
// Sources: ISO 4217 List One published ${published}; Unicode CLDR ${cldrVersion}.

export const ISO_REFERENCE_SOURCES = {
  iso4217Published: ${JSON.stringify(published)},
  cldrVersion: ${JSON.stringify(cldrVersion)},
} as const;

export type IsoCurrency = {
  readonly code: string;
  readonly numericCode: string;
  readonly name: string;
  readonly minorUnits: number;
};

export type IsoCountry = {
  readonly code: string;
  readonly name: string;
  readonly defaultCurrency: string | null;
};

export const ISO_CURRENCIES: readonly IsoCurrency[] = ${JSON.stringify(currencyList, null, 2)};

export const ISO_COUNTRIES: readonly IsoCountry[] = ${JSON.stringify(countries, null, 2)};
`;
mkdirSync(path.join(root, "src/lib/billing/reference"), { recursive: true });
writeFileSync(path.join(root, "src/lib/billing/reference/iso-reference-data.ts"), ts);

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const sql = [
  `-- ISO 4217 List One published ${published}; Unicode CLDR ${cldrVersion}.`,
  "INSERT INTO billing.currencies (code, numeric_code, name, minor_units) VALUES",
  currencyList
    .map((c) => `  (${q(c.code)}, ${q(c.numericCode)}, ${q(c.name)}, ${c.minorUnits})`)
    .join(",\n"),
  "ON CONFLICT (code) DO UPDATE SET numeric_code = EXCLUDED.numeric_code, name = EXCLUDED.name, minor_units = EXCLUDED.minor_units, updated_at = now();",
  "",
  "INSERT INTO billing.countries (code, name, default_currency) VALUES",
  countries
    .map(
      (c) => `  (${q(c.code)}, ${q(c.name)}, ${c.defaultCurrency ? q(c.defaultCurrency) : "NULL"})`,
    )
    .join(",\n"),
  "ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, default_currency = EXCLUDED.default_currency, updated_at = now();",
].join("\n");
process.stdout.write(sql + "\n");
console.error(
  `currencies=${currencyList.length} countries=${countries.length} without_currency=${countries
    .filter((c) => !c.defaultCurrency)
    .map((c) => c.code)
    .join(",")}`,
);
