import { describe, expect, it } from "vitest";
import {
  filterActionNotifications,
  safeNotificationPath,
  sortActionNotifications,
  summarizeActionNotifications,
  mergeNotificationPages,
  parseActionCenterSearch,
  actionNotificationSearchPattern,
  groupNotificationPage,
} from "./notification-utils";

const base = {
  title: "Bill awaiting approval",
  body: "Review supplier bill",
  category: "bill_approval",
  priority: "high",
  read_at: null,
  archived_at: null,
  resolved_at: null,
};
const rows = [
  { ...base, title: "Bill awaiting approval" },
  {
    ...base,
    title: "Overdue invoice",
    body: "Customer payment late",
    category: "overdue_invoice",
    read_at: "2026-10-30T00:00:00Z",
  },
  {
    ...base,
    title: "Bank review",
    category: "bank_reconciliation",
    priority: "critical",
    resolved_at: "2026-10-30T00:00:00Z",
  },
  {
    ...base,
    title: "Document request",
    category: "document_request",
    archived_at: "2026-10-30T00:00:00Z",
  },
];
describe("Action Center filtering", () => {
  it("shows only actionable notifications that have not been archived or resolved", () => {
    expect(
      filterActionNotifications(rows, { view: "action", category: "all", search: "" }),
    ).toHaveLength(2);
  });
  it("only includes unresolved unread notifications in Unread", () => {
    expect(
      filterActionNotifications(rows, { view: "unread", category: "all", search: "" }).map(
        (x) => x.title,
      ),
    ).toEqual(["Bill awaiting approval"]);
  });
  it("filters by module and case-insensitive text", () => {
    expect(
      filterActionNotifications(rows, {
        view: "all",
        category: "overdue_invoice",
        search: "CUSTOMER",
      }).map((x) => x.title),
    ).toEqual(["Overdue invoice"]);
  });
  it("includes resolved work in Completed but excludes archived work", () => {
    expect(
      filterActionNotifications(rows, { view: "completed", category: "all", search: "" }).map(
        (x) => x.title,
      ),
    ).toEqual(["Bank review"]);
  });
  it("includes contact follow-up tasks in their own optional alert category", () => {
    const followUp = {
      ...base,
      title: "Contact follow-up: Call customer",
      body: "Review the task in the contact timeline",
      category: "contact_followup",
    };
    expect(
      filterActionNotifications([...rows, followUp], {
        view: "action",
        category: "contact_followup",
        search: "",
      }).map((item) => item.title),
    ).toEqual(["Contact follow-up: Call customer"]);
    expect(
      filterActionNotifications([{ ...followUp, resolved_at: "2026-11-04T00:00:00Z" }], {
        view: "action",
        category: "contact_followup",
        search: "",
      }),
    ).toHaveLength(0);
  });

  it("shows archived requests only in Archived", () => {
    expect(
      filterActionNotifications(rows, { view: "archived", category: "all", search: "" }).map(
        (x) => x.title,
      ),
    ).toEqual(["Document request"]);
  });
});
describe("notification navigation", () => {
  it("allows known same-origin nested record routes", () => {
    expect(safeNotificationPath("/purchases/bills/88888888-8888-8888-8888-888888888888")).toBe(
      "/purchases/bills/88888888-8888-8888-8888-888888888888",
    );
  });
  it("allows the contact timeline deep link generated by follow-up alerts", () => {
    const path = "/contacts/88888888-8888-8888-8888-888888888888?tab=timeline";
    expect(safeNotificationPath(path)).toBe(path);
  });

  it("rejects external, protocol-relative and script-based links", () => {
    for (const value of [
      "https://evil.example",
      "//evil.example",
      "javascript:alert(1)",
      "/\\evil.example",
      null,
    ]) {
      expect(safeNotificationPath(value)).toBeNull();
    }
  });
});

describe("Action Center triage and overview", () => {
  it("filters actionable alerts by priority without altering existing view rules", () => {
    expect(
      filterActionNotifications(rows, {
        view: "action",
        category: "all",
        search: "",
        priority: "high",
      }).map((row) => row.title),
    ).toEqual(["Bill awaiting approval", "Overdue invoice"]);
    expect(
      filterActionNotifications(rows, {
        view: "critical",
        category: "all",
        search: "",
        priority: "critical",
      }),
    ).toHaveLength(0);
  });

  it("sorts critical and high urgency first, newest first within a priority", () => {
    const sortable = [
      { ...base, id: "low", priority: "low", created_at: "2026-11-06T10:00:00Z" },
      { ...base, id: "high-old", priority: "high", created_at: "2026-11-03T10:00:00Z" },
      { ...base, id: "critical", priority: "critical", created_at: "2026-11-01T10:00:00Z" },
      { ...base, id: "high-new", priority: "high", created_at: "2026-11-05T10:00:00Z" },
    ];
    expect(sortActionNotifications(sortable, "priority").map((x) => x.id)).toEqual([
      "critical",
      "high-new",
      "high-old",
      "low",
    ]);
    expect(sortActionNotifications(sortable, "newest").map((x) => x.id)).toEqual([
      "low",
      "high-new",
      "high-old",
      "critical",
    ]);
    expect(sortActionNotifications(sortable, "oldest").map((x) => x.id)).toEqual([
      "critical",
      "high-old",
      "high-new",
      "low",
    ]);
    expect(sortable[0].id).toBe("low");
  });

  it("counts only active, unread, critical and completed alerts in the loaded window", () => {
    expect(summarizeActionNotifications(rows)).toEqual({
      action: 2,
      unread: 1,
      critical: 0,
      completed: 1,
      archived: 1,
    });
  });
});

describe("Smart Action Center history and bookmarkable filters", () => {
  it("deduplicates changing offset pages without mutating source data", () => {
    const first = [{ id: "a", value: 1 }, { id: "b", value: 2 }];
    const second = [{ id: "b", value: 99 }, { id: "c", value: 3 }];
    expect(mergeNotificationPages([first, second])).toEqual([
      { id: "a", value: 1 },
      { id: "b", value: 2 },
      { id: "c", value: 3 },
    ]);
    expect(second[0].value).toBe(99);
  });

  it("restores whitelisted URL filters and drops unsafe or unexpected values", () => {
    expect(
      parseActionCenterSearch({
        view: "unread",
        category: "contact_followup",
        priority: "critical",
        sort: "oldest",
        q: "  Customer  ",
        other: "ignored",
      }),
    ).toEqual({
      view: "unread",
      category: "contact_followup",
      priority: "critical",
      sort: "oldest",
      q: "  Customer  ",
    });
    expect(
      parseActionCenterSearch({
        view: "admin",
        category: "missing",
        priority: "none",
        sort: "random",
        q: 7,
      }),
    ).toEqual({});
  });

  it("preserves spaces while a user types a multiword search term", () => {
    expect(parseActionCenterSearch({ q: "Invoice " }).q).toBe("Invoice ");
    expect(parseActionCenterSearch({ q: "    " })).toEqual({});
  });

  it("limits saved search terms to 120 characters", () => {
    expect(parseActionCenterSearch({ q: "a".repeat(250) }).q).toHaveLength(120);
  });
});

describe("Action Center server filtering", () => {
  it("escapes SQL LIKE wildcard characters rather than broadening a user's search", () => {
    expect(actionNotificationSearchPattern("  50%_\\  ")).toBe("%50\\%\\_\\\\%");
  });
  it("normalizes case and trims surrounding spaces", () => {
    expect(actionNotificationSearchPattern("  Overdue Invoice  ")).toBe("%overdue invoice%");
  });
});

describe("Action Center grouped page", () => {
  it("groups the current page without reordering alerts within each module", () => {
    const page = [
      { id: "a", category: "bill_approval" },
      { id: "b", category: "bank_reconciliation" },
      { id: "c", category: "bill_approval" },
      { id: "d", category: "document_request" },
    ];
    expect(groupNotificationPage(page)).toEqual([
      { category: "bill_approval", rows: [page[0], page[2]] },
      { category: "bank_reconciliation", rows: [page[1]] },
      { category: "document_request", rows: [page[3]] },
    ]);
    expect(page.map((item) => item.id)).toEqual(["a", "b", "c", "d"]);
  });
  it("handles an empty page", () => {
    expect(groupNotificationPage([])).toEqual([]);
  });
});
