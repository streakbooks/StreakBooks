/**
 * Commercial and module catalogue. New features register here and in
 * billing_features via the entitlement migration pattern.
 * Settings dimensions stay in src/lib/settings/feature-catalog.ts.
 */

export type CatalogueFeature = {
  key: string;
  name: string;
  description: string;
  category: "limit" | "module" | "add_on" | "platform";
  module: string;
  defaultEnabled: boolean;
  metering: "none" | "count" | "bytes" | "minutes";
  costTag: string | null;
  status: "live" | "hidden";
  /** Sold on a plan but not built yet (shown as "coming soon", D19). */
  comingSoon?: true;
};

function planModule(
  key: string,
  name: string,
  description: string,
  module: string,
  comingSoon?: true,
): CatalogueFeature {
  return {
    key,
    name,
    description,
    category: "module",
    module,
    defaultEnabled: false,
    metering: "none",
    costTag: null,
    status: "live",
    ...(comingSoon ? { comingSoon } : {}),
  };
}

