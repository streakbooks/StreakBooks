-- Billing platform, phase 1: private billing schema and ISO reference data.
-- Additive and idempotent. Creates no customer data.
-- The billing schema is not exposed through the Data API; access is through
-- SECURITY DEFINER functions that check permissions.

CREATE SCHEMA IF NOT EXISTS billing;
REVOKE ALL ON SCHEMA billing FROM PUBLIC;
DO $$ BEGIN
  EXECUTE 'REVOKE ALL ON SCHEMA billing FROM anon, authenticated';
EXCEPTION WHEN undefined_object THEN NULL; END $$;

-- ISO 4217 currencies. minor_units is the ISO exponent (0, 2, 3 or 4 decimal places).
CREATE TABLE IF NOT EXISTS billing.currencies (
  code char(3) PRIMARY KEY CHECK (code ~ '^[A-Z]{3}$'),
  numeric_code char(3) NOT NULL CHECK (numeric_code ~ '^[0-9]{3}$'),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
  minor_units smallint NOT NULL CHECK (minor_units BETWEEN 0 AND 4),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ISO 3166-1 alpha-2 countries. billing_enabled stays false until an administrator
-- configures pricing, a payment provider and approved tax rules for the country.
CREATE TABLE IF NOT EXISTS billing.countries (
  code char(2) PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
  default_currency char(3) REFERENCES billing.currencies(code) ON DELETE RESTRICT,
  billing_enabled boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS countries_default_currency_idx ON billing.countries (default_currency);

ALTER TABLE billing.currencies ENABLE ROW LEVEL SECURITY;
ALTER TABLE billing.countries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON billing.currencies, billing.countries FROM PUBLIC;
DO $$ BEGIN
  EXECUTE 'REVOKE ALL ON billing.currencies, billing.countries FROM anon, authenticated';
EXCEPTION WHEN undefined_object THEN NULL; END $$;

