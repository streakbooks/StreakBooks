-- Public read access to reference data (no personal or financial data).
CREATE OR REPLACE FUNCTION public.billing_reference_data()
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT jsonb_build_object(
    'currencies', coalesce((
      SELECT jsonb_agg(jsonb_build_object('code', c.code, 'name', c.name, 'minorUnits', c.minor_units) ORDER BY c.code)
      FROM billing.currencies c WHERE c.is_active), '[]'::jsonb),
    'countries', coalesce((
      SELECT jsonb_agg(jsonb_build_object('code', k.code, 'name', k.name,
        'defaultCurrency', k.default_currency, 'billingEnabled', k.billing_enabled) ORDER BY k.name)
      FROM billing.countries k), '[]'::jsonb)
  );
$$;
REVOKE ALL ON FUNCTION public.billing_reference_data() FROM PUBLIC;
DO $$ BEGIN
  EXECUTE 'GRANT EXECUTE ON FUNCTION public.billing_reference_data() TO anon, authenticated, service_role';
EXCEPTION WHEN undefined_object THEN NULL; END $$;
